# Rebuilds data\shows.js from data\shows.csv.
# Why: web browsers will not let a page opened by double-clicking read shows.csv directly,
# so for local previews the page reads this copy instead. (Once the site is online it reads
# shows.csv directly and this file is not used.)
# Run it via update-shows.bat after every edit to shows.csv.

$ErrorActionPreference = 'Stop'

$root    = Split-Path -Parent $MyInvocation.MyCommand.Path
$csvPath = Join-Path $root 'data\shows.csv'
$jsPath  = Join-Path $root 'data\shows.js'

$csv = [System.IO.File]::ReadAllText($csvPath, [System.Text.Encoding]::UTF8)

# Escape the characters that mean something inside a JavaScript template string.
$bt  = [string][char]96
$csv = $csv.Replace('\', '\\').Replace($bt, '\' + $bt).Replace('${', '\${')

$header = '// AUTO-GENERATED from shows.csv by update-shows.ps1 - do not edit this file; edit shows.csv instead.'
$js = $header + "`r`n" + 'window.SHOWS_CSV = ' + $bt + $csv + $bt + ';' + "`r`n"

[System.IO.File]::WriteAllText($jsPath, $js, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "Updated data\shows.js from data\shows.csv"
